/**
 * Key handling for the chipnet deployer and oracle. WIFs live in packages/oracle/.env (gitignored, never committed).
 *   ORACLE_WIF     signs price messages (its pubkey is PriceContract.oraclePublicKey)
 *   MIGRATION_WIF  holds the oracle migration key NFT (PriceContract.migrateContract authority)
 *   FUNDER_WIF     pays for the deployment and for oracle price-update fees; also receives protocol fees
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  binToHex, decodePrivateKeyWif, encodeLockingBytecodeP2pkh, encodePrivateKeyWif, generatePrivateKey, hash160,
  lockingBytecodeToCashAddress, secp256k1,
} from '@bitauth/libauth';
import { SignatureTemplate } from 'cashscript';

export const ORACLE_PKG_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');
export const REPO_ROOT = join(ORACLE_PKG_DIR, '..', '..');
export const DEFAULT_ENV_PATH = join(ORACLE_PKG_DIR, '.env');

export type KeyName = 'ORACLE_WIF' | 'MIGRATION_WIF' | 'FUNDER_WIF';
export const KEY_NAMES: KeyName[] = ['ORACLE_WIF', 'MIGRATION_WIF', 'FUNDER_WIF'];

export interface KeyPair {
  wif: string;
  privateKey: Uint8Array;
  publicKey: Uint8Array;
  publicKeyHex: string;
  lockingBytecode: Uint8Array;
  lockingBytecodeHex: string;
  signer: SignatureTemplate;
  /** cash address (no token support) for the given prefix */
  address(prefix?: 'bitcoincash' | 'bchtest' | 'bchreg'): string;
  tokenAddress(prefix?: 'bitcoincash' | 'bchtest' | 'bchreg'): string;
}

export function keyFromPrivateKey(privateKey: Uint8Array): KeyPair {
  const publicKey = secp256k1.derivePublicKeyCompressed(privateKey);
  if (typeof publicKey === 'string') throw new Error(publicKey);
  const lockingBytecode = encodeLockingBytecodeP2pkh(hash160(publicKey));
  const wif = encodePrivateKeyWif(privateKey, 'testnet');
  const addr = (prefix: 'bitcoincash' | 'bchtest' | 'bchreg', tokenSupport: boolean) => {
    const r = lockingBytecodeToCashAddress({ bytecode: lockingBytecode, prefix, tokenSupport });
    if (typeof r === 'string') throw new Error(r);
    return r.address;
  };
  return {
    wif, privateKey, publicKey, publicKeyHex: binToHex(publicKey),
    lockingBytecode, lockingBytecodeHex: binToHex(lockingBytecode),
    signer: new SignatureTemplate(privateKey),
    address: (prefix = 'bchtest') => addr(prefix, false),
    tokenAddress: (prefix = 'bchtest') => addr(prefix, true),
  };
}

export function keyFromWif(wif: string): KeyPair {
  const decoded = decodePrivateKeyWif(wif);
  if (typeof decoded === 'string') throw new Error(`invalid WIF: ${decoded}`);
  return keyFromPrivateKey(decoded.privateKey);
}

export const newKey = (): KeyPair => keyFromPrivateKey(generatePrivateKey());

function parseEnv(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (m) out[m[1]!] = m[2]!.replace(/^['"]|['"]$/g, '');
  }
  return out;
}

/** Read the three keys from process.env or the .env file; with `generate`, create the missing ones and append them. */
export function loadKeys(opts: { envPath?: string; generate?: boolean } = {}): Record<KeyName, KeyPair> {
  const envPath = opts.envPath ?? DEFAULT_ENV_PATH;
  const fileText = existsSync(envPath) ? readFileSync(envPath, 'utf8') : '';
  const fileEnv = parseEnv(fileText);
  const result = {} as Record<KeyName, KeyPair>;
  const appended: string[] = [];
  for (const name of KEY_NAMES) {
    const wif = process.env[name] ?? fileEnv[name];
    if (wif) { result[name] = keyFromWif(wif); continue; }
    if (!opts.generate) throw new Error(`${name} missing: set it in ${envPath} (run the deployer once to generate keys)`);
    const k = newKey();
    result[name] = k;
    appended.push(`${name}=${k.wif}`);
  }
  if (appended.length) {
    const header = fileText ? '' : '# sigsig chipnet keys. NEVER COMMIT. Generated by packages/oracle deployer.\n';
    const sep = fileText && !fileText.endsWith('\n') ? '\n' : '';
    writeFileSync(envPath, `${fileText}${sep}${header}${appended.join('\n')}\n`, { mode: 0o600 });
    console.log(`generated ${appended.length} key(s) into ${envPath}`);
  }
  return result;
}
